// ---- the authored room frame ----------------------------------------------
//
// Everything in this file is written in the *authored* room frame, the one
// 60_interiors.py builds in and the HANDOFF §4 documents: +x into the room,
// +y to the left along the entrance wall, +z up.
//
// That is NOT the room group's own local frame. The glTF exporter maps
// Blender (x, y, z) -> (x, z, -y), so the group's local axes are
// (x into the room, y up, z along the wall to the right), and
// interiors.place() keeps the conversion in exactly one place: room.local().
//
// Applying that swap zero times is P2-056 all over again, and it shipped
// here: doors.js fed authored vectors straight to group.localToWorld(), so
// "1.7 m up" became 1.7 m sideways. Measured, on all six rooms,
// room.local(0,0,1.7) and group.localToWorld(0,0,1.7) differed by exactly
// 1.70 m of height — which put every walk-in 1.70 m to the side of a 2.20 m
// opening, 0.60 m past its edge, walking into uncut wall. The trace: the
// camera pinned at room-local x = -0.721 m for 65 consecutive frames with
// the door fully open.
//
// So: authored coordinates cross into group space through authToLocal() and
// come back through localToAuth(), and nowhere else. The door assembly gets
// the same swap as a single -90 deg rotation about x on its own child group,
// which is the matrix form of (x, y, z) -> (x, z, -y).

// Authored (x into, y left, z up) -> room-group local (x into, y up, z right).
export function authToLocal(x, y, z, out) { return out.set(x, z, -y) }

// Room-group local -> authored.
export function localToAuth(v, out) { return out.set(v.x, -v.z, v.y) }

