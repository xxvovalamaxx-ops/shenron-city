// doors.js — Phase 3B: real doorways, cut into the buildings the hero
// corridor touches, and walk-in interiors with no keypress and no teleport.
//
// What this replaces: interiors.js's E-at-a-marked-threshold entry, which was
// honest about the geometry (the shells were solid) but is now the most
// visible piece of honesty debt left — the HANDOFF calls it out verbatim.
//
// What this does, per configured building:
//
//   1. Cut a real rectangular opening into the building's baked tile wall at
//      street level (exact 2D rect subtraction in the wall plane, doors-math).
//      The walk collider probes the actual tile meshes, so a real hole in the
//      mesh is a real hole in the collision: no hit filter, no fake doorway.
//   2. Punch the matching opening in the room's glazed entrance wall.
//   3. Build the door assembly in the opening: frame (jambs, header, sill),
//      an automatic sliding leaf with a glass pane, a header track, and a lit
//      ceiling panel over the threshold. All procedural, in the same palette
//      as the authored interiors — no third-party asset enters the build.
//   4. Run a door state machine per doorway: closed -> opening -> open ->
//      closing -> closed, driven by a trigger volume; an obstruction that
//      reopens a closing door; a dwell that lets the player pass; a pause
//      freeze; and persisted state across reloads.
//   5. Detect the player crossing the wall plane through the opening and flip
//      interiors.inside physically — the camera never jumps, and walking back
//      out reverses it (reverse traversal).
//   6. Preload the interior when the player is near the threshold: the room
//      group becomes visible and the interior lamp ramps up before the
//      threshold is crossed, so the walk-in is continuous and there is no
//      black void behind the opening.
//   7. Physical lift rides for the interior link thresholds (HQ lobby <->
//      Floor 45, home lobby <-> penthouse) in the corridor's own cab, so the
//      interior transitions that remain are rides, not teleports.
//
// The corridor buildings are configured in data-driven form
// (data/doors/doors.json, generated by scripts/phase2/68_build_doors.py) so
// the same pipeline can be pointed at the ~660 subway-adjacent and
// ground-floor-retail buildings later. Nothing here hard-codes a building.
//
// Verification lives in verify() (measured numbers, per HANDOFF §0) and the
// headless run in scripts/qa/doorcheck-run.mjs.

