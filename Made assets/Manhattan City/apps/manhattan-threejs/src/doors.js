// Remove only the triangles lying *wholly* inside `box` — a containment test,
// never an AABB-overlap test. Overlap is what the first pass of this file did
// and it is far too coarse against merged tile geometry, where one triangle
// can be a whole ground-to-roof wall quad: a face that merely reaches into
// the doorway volume (a neighbour's wall running past it) must keep its
// geometry, and only what is actually in the way comes out. `allow(bid)`
// gates which building ids may be removed.
export function cutContained(geometry, box, allow = () => true) {
  const pos = geometry.attributes.position
  const bidAttr = geometry.attributes._bid || geometry.attributes._BID
  const idx = geometry.index
  const tris = idx ? idx.count / 3 : pos.count / 3
  const keep = []
  let removed = 0
  for (let t = 0; t < tris; t++) {
    const a = idx ? idx.getX(t * 3) : t * 3
    const b = idx ? idx.getX(t * 3 + 1) : t * 3 + 1
    const c = idx ? idx.getX(t * 3 + 2) : t * 3 + 2
    let inside = true
    for (const i of [a, b, c]) {
      const x = pos.getX(i); const y = pos.getY(i); const z = pos.getZ(i)
      if (x < box.min[0] || x > box.max[0] || y < box.min[1] ||
          y > box.max[1] || z < box.min[2] || z > box.max[2]) {
        inside = false
        break
      }
    }
    if (inside && bidAttr && !allow(Math.round(bidAttr.getX(a)))) inside = false
    if (inside) removed++
    else keep.push([a, b, c])
  }
  if (!removed) return { geometry, removed: 0 }
  const out = cloneGeometry(geometry)
  const outIdx = []
  for (const [a, b, c] of keep) outIdx.push(a, b, c)
  out.setIndex(outIdx)
  out.computeBoundingSphere()
  return { geometry: out, removed }
}

// Punch a rectangular hole in a room's glazed entrance wall.
//
// The glaze is authored as a plane at the room's x ~ 0, so this is the same
// exact 2D rect subtraction the building wall gets (doors-math), done in the
// wall's own (u, v) = (mesh-local z along the wall, mesh-local y up).
//
// Dropping triangles by AABB cannot do this job. The lobby's glaze is a
// *single* 24 m quad, so removing every triangle whose AABB touches the door
// box deleted the entire pane — measured at 0 glaze triangles remaining on
// all four doorways, which is not a doorway, it is a missing wall. `rect` is
// in mesh-local (z, y);
// only faces within xMax of the entrance plane are considered, so a room
// whose glaze wraps a second wall keeps that wall.
export function cutGlazeRect(geometry, rect, xMax = 0.5) {
  const pos = geometry.attributes.position
  const idx = geometry.index
  const tris = idx ? idx.count / 3 : pos.count / 3
  const outTris = []
  const newVerts = []
  const newNorms = []
  const newCols = []
  const nrm = geometry.attributes.normal
  const col = geometry.attributes.color
  let cut = 0
  let removed = 0

  for (let t = 0; t < tris; t++) {
    const a = idx ? idx.getX(t * 3) : t * 3
    const b = idx ? idx.getX(t * 3 + 1) : t * 3 + 1
    const c = idx ? idx.getX(t * 3 + 2) : t * 3 + 2
    const xs = [pos.getX(a), pos.getX(b), pos.getX(c)]
    if (Math.max(...xs) > xMax) { outTris.push([a, b, c]); continue }
    // (u, v) = (along the wall, up)
    const tri = [
      [pos.getZ(a), pos.getY(a)],
      [pos.getZ(b), pos.getY(b)],
      [pos.getZ(c), pos.getY(c)],
    ]
    if (!rectsOverlap(polyBox(tri), rect)) { outTris.push([a, b, c]); continue }
    const pieces = cutTriangle(tri, rect)
    if (pieces === null) { outTris.push([a, b, c]); continue }
    if (!pieces.length) { removed++; continue }
    cut++

    // the entrance plane's x is whatever this face sits on (0.02 authored),
    // taken from the face itself so a slightly offset pane stays put
    const xPlane = (xs[0] + xs[1] + xs[2]) / 3
    const n0 = nrm ? [nrm.getX(a), nrm.getY(a), nrm.getZ(a)] : null
    const c0 = col ? [col.getX(a), col.getY(a), col.getZ(a)] : null
    const base = pos.count + newVerts.length / 3
    let k = 0
    for (const piece of pieces) {
      const off = k
      for (const [u, v] of piece) {
        newVerts.push(xPlane, v, u)
        if (n0) newNorms.push(n0[0], n0[1], n0[2])
        if (c0) newCols.push(c0[0], c0[1], c0[2])
        k++
      }
      for (let i = 1; i < piece.length - 1; i++) {
        outTris.push([base + off, base + off + i, base + off + i + 1])
      }
    }
  }

  if (!cut && !removed) return { geometry, cut: 0, removed: 0, kept: tris }
  const out = cloneGeometry(geometry)
  const nv = newVerts.length / 3
  extendAttribute(out.attributes.position, nv, (i) => newVerts[i])
  if (out.attributes.normal) {
    extendAttribute(out.attributes.normal, nv, (i) => newNorms[i] ?? 0)
  }
  if (out.attributes.color) {
    extendAttribute(out.attributes.color, nv, (i) => newCols[i] ?? 1)
  }
  for (const [name, attr] of Object.entries(out.attributes)) {
    if (name === 'position' || name === 'normal' || name === 'color') continue
    extendAttribute(attr, nv, null)
  }
  const outIdx = []
  for (const [a, b, c] of outTris) outIdx.push(a, b, c)
  out.setIndex(outIdx)
  out.computeBoundingSphere()
  out.computeBoundingBox()
  return { geometry: out, cut, removed, kept: outTris.length }
}

// Grow a BufferAttribute by `extra` items, filling from fillFn (index into
// the appended run) or with zeroes.
export function extendAttribute(attr, extra, fillFn) {
  const item = attr.itemSize
  const old = attr.array
  const arr = new (old.constructor)(old.length + extra * item)
  arr.set(old)
  for (let i = 0; i < extra * item; i++) {
    arr[old.length + i] = fillFn ? fillFn(i) : 0
  }
  attr.array = arr
  attr.count = arr.length / item
  attr.needsUpdate = true
  return attr
}

// Clone a geometry's attributes into a new geometry. The caller re-indexes.
export function cloneGeometry(geometry) {
  const out = new THREE.BufferGeometry()
  for (const [name, attr] of Object.entries(geometry.attributes)) {
    out.setAttribute(name, attr.clone())
  }
  return out
}

// Cut a rectangular doorway out of the wall faces of one building inside a
// merged tile mesh. `bidSet` maps vertex index -> belongs to the building
// (with .bid on it); `frame` is the wall frame (world); `rect` is the door
// rect in (u, v). Returns { geometry, cut, removed } — the new geometry, or
// the same geometry when nothing was cut. The appended split vertices copy
// the colour of the face they came from, so the facade shading is seamless.
//
// opts.band = { min, max } bounds how far along the frame normal a face may
// sit and still be cut. Without it the frame is an infinite plane: Manhattan's
// facades are all parallel to each other, so a door rect punched "in the wall"
// also punches phantom doorways through every parallel facade down the block
// that happens to project into the same (u, v). Always pass a band.
//
// Faces are cut whichever way they are wound, as long as they are roughly
// parallel to the wall (|dot| > 0.5). The first pass cut only faces whose
// normal *opposed* the frame's — but the frame is built from a face of that
// same wall, so its own normal scores +1 and the wall the doorway is in was
// the one thing the cut skipped. Measured: 2 of 48 building faces reached the
// facing test at the tower lobby and both were rejected by it. Localisation
// is the band's and the aabb's job, not the winding's; a doorway passage has
// to clear whatever is in it, including a neighbour's wall wound back toward
// the door (the market's block shares its outline with an adjacent school).
//
// opts.aabb = { min, max } is the cheap early-out and should always be given.
// A resident tile mesh holds ~10^5 triangles and its bounding box spans a
// 1,400 m tile, so without a per-triangle box test every doorway pays normal
// dots and plane projections over the whole tile — measured as minutes per
// cut, which is what turned the passage sweep into a hang.
export function cutWallInMesh(geometry, bidSet, frame, rect, opts = {}) {
  const band = opts.band || null
  const aabb = opts.aabb || null
  const pos = geometry.attributes.position
  const nrm = geometry.attributes.normal
  const col = geometry.attributes.color
  const idx = geometry.index
  const tris = idx ? idx.count / 3 : pos.count / 3

  const v = (i, out) => {
    out[0] = pos.getX(i); out[1] = pos.getY(i); out[2] = pos.getZ(i)
    return out
  }
  const p0 = [0, 0, 0]; const p1 = [0, 0, 0]; const p2 = [0, 0, 0]
  const outTris = []
  const newVerts = []
  const newNorms = []
  const newCols = []
  const newBids = []
  const srcBid = geometry.attributes._bid || geometry.attributes._BID
  let cut = 0
  let removed = 0
  // Why faces were passed over. A cut that reports zero is otherwise silent
  // about whether it found no building, no wall facing the right way, nothing
  // in the depth band, or nothing overlapping the rect — four very different
  // bugs. Cheap counters beat re-deriving it from the outside.
  // missAxis is a bitmask tally (1 = x, 2 = y, 4 = z) of which axis put a
  // face outside the door box — which is the difference between "the frame is
  // in the wrong place" and "the frame is in the wrong coordinate space".
  const why = { total: tris, mine: 0, box: 0, facing: 0, band: 0, rect: 0,
    missAxis: {} }

  for (let t = 0; t < tris; t++) {
    const a = idx ? idx.getX(t * 3) : t * 3
    const b = idx ? idx.getX(t * 3 + 1) : t * 3 + 1
    const c = idx ? idx.getX(t * 3 + 2) : t * 3 + 2
    if (!bidSet.has(a) || !bidSet.has(b) || !bidSet.has(c)) {
      outTris.push([a, b, c])
      continue
    }
    why.mine++
    v(a, p0); v(b, p1); v(c, p2)
    if (aabb) {
      let miss = 0
      for (let k = 0; k < 3; k++) {
        if (Math.max(p0[k], p1[k], p2[k]) < aabb.min[k] ||
            Math.min(p0[k], p1[k], p2[k]) > aabb.max[k]) {
          miss |= (1 << k)
        }
      }
      if (miss) {
        why.missAxis[miss] = (why.missAxis[miss] || 0) + 1
        outTris.push([a, b, c])
        continue
      }
    }
    why.box++
    const n = triNormal3(p0, p1, p2)
    const dot = n[0] * frame.normal[0] + n[1] * frame.normal[1] +
      n[2] * frame.normal[2]
    if (Math.abs(dot) < 0.5) {
      outTris.push([a, b, c])
      continue
    }
    why.facing++
    if (band) {
      // depth along the frame normal, from the face centroid
      const cxm = (p0[0] + p1[0] + p2[0]) / 3 - frame.o[0]
      const cym = (p0[1] + p1[1] + p2[1]) / 3 - frame.o[1]
      const czm = (p0[2] + p1[2] + p2[2]) / 3 - frame.o[2]
      const depth = cxm * frame.normal[0] + cym * frame.normal[1] +
        czm * frame.normal[2]
      if (depth < band.min || depth > band.max) {
        outTris.push([a, b, c])
        continue
      }
    }
    why.band++
    const u0 = frameProject(frame, p0)
    const u1 = frameProject(frame, p1)
    const u2 = frameProject(frame, p2)
    const tb = polyBox([u0, u1, u2])
    if (!rectsOverlap(tb, rect)) { outTris.push([a, b, c]); continue }
    why.rect++

    const pieces = cutTriangle([u0, u1, u2], rect)
    if (pieces === null) { outTris.push([a, b, c]); continue }
    if (!pieces.length) { removed++; continue }
    cut++

    // The kept pieces, fanned into triangles and appended as their own
    // vertices.
    //
    // This used to build a fan index over a shared vertex list and then emit
    // the triangles as [base + i, base + i + 1, base + i + 2] with `i` running
    // over the fan's *values* rather than its positions — so the rebuilt faces
    // referenced whatever vertices happened to sit at those offsets. The
    // result is geometry that has nothing to do with the wall, and some of it
    // lands back across the opening: measured, a collision probe from inside
    // the home lobby hit tile geometry at (u, v) = (0.00, 0.99), dead centre
    // of a 2.2 x 2.5 m doorway that rays at other heights passed straight
    // through. Emitting three fresh vertices per triangle costs a few
    // duplicates and cannot be indexed wrong.
    const c0 = col ? [col.getX(a), col.getY(a), col.getZ(a)] : null
    // the face's own building id, not the caller's: a passage cut runs over
    // the *neighbours'* faces, and stamping them with the target's bid would
    // relabel another building's facade (Draco quantises _BID, so round it —
    // P2-060)
    const b0 = srcBid ? Math.round(srcBid.getX(a))
      : (bidSet.bid ?? 0)
    for (const piece of pieces) {
      for (let i = 1; i < piece.length - 1; i++) {
        const base = pos.count + newVerts.length / 3
        for (const [u, vv] of [piece[0], piece[i], piece[i + 1]]) {
          const p = framePoint(frame, u, vv)
          newVerts.push(p[0], p[1], p[2])
          newNorms.push(n[0], n[1], n[2])
          newBids.push(b0)
          if (c0) newCols.push(c0[0], c0[1], c0[2])
        }
        outTris.push([base, base + 1, base + 2])
      }
    }
  }

  if (!cut && !removed) return { geometry, cut: 0, removed: 0, why }

  const out = cloneGeometry(geometry)
  const posA = out.attributes.position
  const nrmA = out.attributes.normal
  const colA = out.attributes.color
  const nv = newVerts.length / 3

  const extend = extendAttribute
  extend(posA, nv, (i) => newVerts[i])
  if (nrmA) extend(nrmA, nv, (i) => newNorms[i])
  if (colA) extend(colA, nv, (i) => newCols[i])
  const bidName = out.attributes._bid ? '_bid' : '_BID'
  if (bidName && out.attributes[bidName]) {
    extend(out.attributes[bidName], nv, (i) => newBids[i])
  }
  const other = []
  for (const [name, attr] of Object.entries(out.attributes)) {
    if (name === 'position' || name === 'normal' || name === 'color' ||
        name === bidName) continue
    other.push([name, attr])
  }
  for (const [name, attr] of other) extend(attr, nv, null)

  const outIdx = []
  for (const [a, b, c] of outTris) outIdx.push(a, b, c)
  out.setIndex(outIdx)
  out.computeBoundingSphere()
  out.computeBoundingBox()
  return { geometry: out, cut, removed, why }
}

