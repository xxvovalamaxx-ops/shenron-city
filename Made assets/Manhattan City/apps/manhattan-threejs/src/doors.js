  async load(url = '/doors/doors.json') {
    const data = await fetch(url).then((r) => (r.ok ? r.json() : null))
      .catch(() => null)
    if (!data || !Array.isArray(data.doors)) {
      console.warn('[doors] no doors.json; doorways disabled')
      return this
    }
    // The expansion set (68_build_doors.py --expansion, 631 subway-tranche
    // buildings) is generated with runtimeEnabled: false and lives in its own
    // file. If it is ever pointed at this loader by mistake, refuse it: those
    // entries have no interior room, and cutting a hole into a solid building
    // is worse than no doorway. The gate is a room behind the opening, not a
    // flag.
    if (data.runtimeEnabled === false) {
      console.warn('[doors]', url, 'is marked runtimeEnabled: false',
        `(${data.doors.length} entries); doorways disabled`)
      return this
    }
    for (const cfg of data.doors) this._add(cfg)
    for (const d of this.doors) {
      // the interior answers no keypress once its doorway is real
      d.room.doorway = true
      // the wall cut may rotate the room to a clear frontage, and it measures
      // the wall distance the assembly and the crossing plane are placed
      // from, so the assembly is built after it, from the final matrix. Both
      // kinds cut: a recess is a wall like any other (§ _cutWall).
      this._cutWall(d)
      this._buildAssembly(d)
      this._cutRoomGlass(d)
    }
    this.ready = this.doors.length > 0
    this.stats.doors = this.doors.length
    // tiles can arrive after boot; re-cut a door's wall when its tile loads
    this.streamer.onReady.push(() => {
      for (const d of this.doors) if (!d.cut) this._findAndCut(d)
    })
    console.info('[doors]', this.doors.length, 'doorways configured:',
      this.doors.map((d) => `${d.key} (bid ${d.bid})`).join(', '))
    if (this._restored.length) {
      // timing-free evidence for the headless runner's reload check
      window.__doorsBootState = this._restored
    }
    return this
  }

